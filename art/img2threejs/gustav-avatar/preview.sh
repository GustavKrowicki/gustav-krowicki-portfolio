#!/bin/sh
# Authoring preview (NOT a review pass): generate the whole figure from a scratch copy of the spec whose first
# pass includes every component, and sync it into the portfolio so the lab shows it. The real pass factories
# come from pass.sh gen <pass-id>, which only ever builds the unlocked pass.
set -e
W="$(cd "$(dirname "$0")" && pwd)"
F="${IMG2THREEJS:-$HOME/.claude/skills/img2threejs}/forge"
cd "$W"
python3 - <<'PY'
import json
s = json.load(open("object-sculpt-spec.json"))
ids = [c["id"] for c in s["componentTree"]]
for bp in s["buildPasses"]:
    bp["componentRefs"] = ids
s["reviewHistory"] = []
json.dump(s, open("_preview-spec.json", "w"), indent=2)
PY
python3 $F/stage3_build/orchestrate_passes.py sync _preview-spec.json --in-place >/dev/null
python3 $F/stage3_build/generate_threejs_factory.py _preview-spec.json --out src/preview.ts --pass-id blockout --force | tail -1 | cut -c1-80
REPO="$(cd "$W/../../.." && pwd)"
{ echo "/* eslint-disable @typescript-eslint/no-explicit-any */"; echo "// GENERATED by img2threejs from art/img2threejs/gustav-avatar (build_spec.py) — AUTHORING PREVIEW, not a reviewed pass."; cat "$W/src/preview.ts"; } > "$REPO/lib/city/models/gustavAvatar.ts"
echo "preview synced"
