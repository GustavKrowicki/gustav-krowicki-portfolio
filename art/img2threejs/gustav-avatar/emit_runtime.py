"""Emit lib/city/models/gustavAvatarRuntime.ts with the plugin's Stage R5 runtime emitter.

Loop flags come from the clip-measure result (clip-features.json, written by anim_clip_features.py from the
browser-sampled clips). Before a measurement exists every clip is emitted with loop = null, which the runtime
plays as LoopOnce: unmeasured is never silently a loop.

Usage: python3 -I emit_runtime.py <workspace> <repo-root>
"""
import json
import os
import sys

W, REPO = sys.argv[1], sys.argv[2]
sys.path.insert(0, os.path.expanduser("~/.img2/plugins/character/tools"))
from anim_emit_runtime import emit_animation_runtime  # noqa: E402

authored = [("idle", "Idle"), ("walk", "Walk (root motion)"), ("walk-in-place", "Walk in place (sprites)")]
measured = {}
path = f"{W}/clip-features.json"
if os.path.exists(path):
    doc = json.load(open(path))
    for clip in doc.get("clips", []):
        measured[clip.get("sourceName")] = clip
clips = []
for cid, label in authored:
    m = measured.get(cid, {})
    loop = (m.get("name") or {}).get("loop", m.get("loop"))
    clips.append({"id": cid, "label": label, "sourceName": cid,
                  "duration": (m.get("features") or {}).get("duration", 3.0 if cid == "idle" else 1.0),
                  "loop": loop if isinstance(loop, bool) else None})
src = emit_animation_runtime(clips, {"gate_sample_count": 5})
# three's type definitions (r182) omit KeyframeTrack.createInterpolant, which exists at runtime; cast for tsc only.
src = src.replace("const interpolant = track.createInterpolant();",
                  "const interpolant = (track as unknown as { createInterpolant(): THREE.Interpolant }).createInterpolant();")
header = ("/* eslint-disable */\n// GENERATED by the img2 character plugin (tools/anim_emit_runtime.py) via "
          "art/img2threejs/gustav-avatar/emit_runtime.py -- regenerate, do not hand-edit.\n")
open(f"{REPO}/lib/city/models/gustavAvatarRuntime.ts", "w").write(header + src)
print(json.dumps([(c["id"], c["loop"]) for c in clips]))
