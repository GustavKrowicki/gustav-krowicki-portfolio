"""Room-skeleton layout for the roof-off LEGO HQ (board 02b, card B2).

Reads the campus block outlines from ../lego-campus/measure/plan.json (building grid, already square to the
grid in plan coordinates u, v), fits them into the 7x7 footprint (x, z in [-0.48, 0.48], 1.0 = footprint)
and writes lib/city/models/legoCampusRoomsLayout.ts. The fit stretches v more than u, so rooms get the depth
they need at city scale. Run: python3 -I art/img2threejs/lego-campus-rooms/gen_layout.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
plan = {r["id"]: r for r in json.load(open(HERE.parent / "lego-campus" / "measure" / "plan.json"))}

# block id -> (key, room label, kind, storeys); kind decides materials, room=None means no room yet
BLOCKS = [
    ("b-main-2", "west-wing", None, "wing", 2),
    ("b-main-1", "north-wing", "workshop", "wing", 2),
    ("b-high-1", "north-bar", "workshop", "yellow", 3),
    ("b-mid-0", "south-west-wing", "recommendation-studio", "wing", 2),
    ("b-main-0", "round-building", "systems-map-room", "wing", 2),
    ("b-mid-1", "south-east-wing", "launch-room", "wing", 2),
    ("b-low-0", "terrace-building", "ai-lab", "terrace", 1),
    ("b-high-0", "atrium", "lobby", "glass", 3),
    ("b-top-0", "entrance-block", "entrance", "yellow", 3),
]

ids = [b[0] for b in BLOCKS]
us = [p[0] for i in ids for p in plan[i]["outline"]]
vs = [p[1] for i in ids for p in plan[i]["outline"]]
cu, cv = (min(us) + max(us)) / 2, (min(vs) + max(vs)) / 2
su, sv = 0.96 / (max(us) - min(us)), 0.96 / (max(vs) - min(vs))


def tx(ring):
    return [[round((u - cu) * su, 4), round((v - cv) * sv, 4)] for u, v in ring]


out = []
for pid, key, room, kind, storeys in BLOCKS:
    r = plan[pid]
    out.append({"key": key, "room": room, "kind": kind, "storeys": storeys,
                "outline": tx(r["outline"]), "holes": [tx(h) for h in (r.get("holes") or [])]})

ts = (
    "// GENERATED by art/img2threejs/lego-campus-rooms/gen_layout.py from the campus plan. Do not edit.\n"
    "// Footprint units: 1.0 = the 7x7 tile footprint; x east, z south. Stretch u x%.3f, v x%.3f.\n\n"
    "export type CampusBlock = {\n  key: string;\n  room: string | null;\n  kind: 'wing' | 'yellow' | 'glass' | 'terrace';\n"
    "  storeys: number;\n  outline: [number, number][];\n  holes: [number, number][][];\n};\n\n"
    "export const CAMPUS_BLOCKS: CampusBlock[] = %s;\n" % (su, sv, "[\n" + ",\n".join("  " + json.dumps(b) for b in out) + ",\n]")
)
(ROOT / "lib/city/models/legoCampusRoomsLayout.ts").write_text(ts)
print("blocks", len(out), "stretch", round(su, 3), round(sv, 3))
